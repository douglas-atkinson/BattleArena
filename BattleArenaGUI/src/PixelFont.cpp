void addQuad(sf::VertexArray& va, sf::Vector2f p, float size, sf::Color c)
{
    const sf::Vector2f a = p, b{p.x + size, p.y}, d{p.x, p.y + size}, e{p.x + size, p.y + size};
    va.append({a, c});
    va.append({b, c});
    va.append({d, c});
    va.append({b, c});
    va.append({e, c});
    va.append({d, c});
}
